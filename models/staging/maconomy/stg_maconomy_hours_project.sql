with source as (
    select
        rowid,
        instancekey,
        entrynumber,
        jobnumber,
        journalnumber,
        journallinenumber,
        transactionnumber,
        transactiontype,
        postingdate,
        entrydate,
        financeentrydate,
        companynumber,
        activitynumber,
        activitytype,
        activitytext,
        taskname,
        text,
        employeenumber,
        suppliernumber,
        numberregistered,
        costprice,
        costpricereg,
        originalcostprice,
        markuppercentage,
        billingpriceregbase,
        billingpriceupdownbase,
        invoicenumber,
        locationname,
        entityname,
        projectname,
        transactiontimestamp,
        ingested_at,
        ingestion_run_id,
        source_system,
        source_object
    from {{ source('maconomy', 'jobentry') }}
    where entrynumber >= 0
),

renamed as (
    select
        rowid                    as job_entry_row_id,
        instancekey              as job_entry_instance_key,
        entrynumber              as entry_number,
        jobnumber                as job_number,
        journalnumber            as journal_number,
        journallinenumber        as journal_line_number,
        transactionnumber        as transaction_number,
        transactiontype          as transaction_type,
        postingdate              as posting_date,
        entrydate                as entry_date,
        financeentrydate         as finance_entry_date,
        companynumber            as company_number,
        activitynumber           as activity_number,
        activitytype             as activity_type,
        activitytext             as activity_text,
        taskname                 as task_name,
        text                     as entry_text,
        employeenumber           as employee_number,
        suppliernumber           as supplier_number,
        numberregistered         as number_registered,
        costprice                as cost_price,
        costpricereg             as cost_price_reg,
        originalcostprice        as original_cost_price,
        markuppercentage         as markup_percentage,
        billingpriceregbase      as billing_price_reg_base,
        case
            when trim(coalesce(invoicenumber, '')) != '' then 0.0
            else billingpriceupdownbase
        end                      as billing_price_up_down_base,
        invoicenumber            as invoice_number,
        locationname             as location_name,
        entityname               as entity_name,
        projectname              as project_name,
        transactiontimestamp     as source_transaction_timestamp,
        ingested_at,
        ingestion_run_id,
        source_system,
        source_object
    from source
)

select * from renamed
